<?php
function date_ukr($date) {
    $date = strtotime(str_replace('-','/', $date));
    $d = date('d', $date);
    $m = date('n', $date);
    $y = date('Y', $date);
    $months = array('-', 'січня', 'лютого', 'березня', 'квітня', 'травня', 'червня', 'липня', 'серпня', 'вересня', 'жовтня', 'листопада', 'грудня');
    return $d . ' ' . $months[$m] . ' ' . $y;
}

function num2str($num) {
    $nul='нуль';
    $ten=array(
        array('','один','два','три','чотири','п\'ять','шість','сім', 'вісім','дев\'ять'),
        array('','одна','дві','три','чотири','п\'ять','шість','сім', 'вісім','дев\'ять'),
    );
    $a20=array('десять','одинадцять','дванадцять','тринадцять','чотирнадцять' ,'п\'ятнадцять','шістнадцять','сімнадцять','вісімнадцять','дев\'ятнадцять');
    $tens=array(2=>'двадцять','тридцять','сорок','п\'ятьдесят','шістдесят','сімдесят' ,'вісімдесят','дев\'яносто');
    $hundred=array('','сто','двісті','триста','чотириста','п\'ятсот','шістсот', 'сімсот','вісімсот','дев\'ятсот');
    $unit=array( // Units
        array('копійка' ,'копійки' ,'копійок',	 1),
        array('гривня'   ,'гривень','гривень'    ,0),
        array('тисяч'  ,'тисячі'  ,'тисяч'     ,1),
        array('мільйон' ,'мільйона','мільйонів' ,0),
        array('мільярд','мільйардів','мільйардів',0),
    );
    //
    list($rub,$kop) = explode('.',sprintf("%015.2f", floatval($num)));
    $out = array();
    if (intval($rub)>0) {
        foreach(str_split($rub,3) as $uk=>$v) { // by 3 symbols
            if (!intval($v)) continue;
            $uk = sizeof($unit)-$uk-1; // unit key
            $gender = $unit[$uk][3];
            list($i1,$i2,$i3) = array_map('intval',str_split($v,1));
            // mega-logic
            $out[] = $hundred[$i1]; # 1xx-9xx
            if ($i2>1) $out[]= $tens[$i2].' '.$ten[$gender][$i3]; # 20-99
            else $out[]= $i2>0 ? $a20[$i3] : $ten[$gender][$i3]; # 10-19 | 1-9
            // units without rub & kop
            if ($uk>1) $out[]= morph($v,$unit[$uk][0],$unit[$uk][1],$unit[$uk][2]);
        } //foreach
    }
    else $out[] = $nul;
    $out[] = morph(intval($rub), $unit[1][0],$unit[1][1],$unit[1][2]); // rub
    $out[] = $kop.' '.morph($kop,$unit[0][0],$unit[0][1],$unit[0][2]); // kop
    return trim(preg_replace('/ {2,}/', ' ', join(' ',$out)));
}

/**
 * Склоняем словоформу
 * @ author runcore
 */
function morph($n, $f1, $f2, $f5) {
    $n = abs(intval($n)) % 100;
    if ($n>10 && $n<20) return $f5;
    $n = $n % 10;
    if ($n>1 && $n<5) return $f2;
    if ($n==1) return $f1;
    return $f5;
}

